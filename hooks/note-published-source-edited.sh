#!/bin/bash
# PostToolUse hook (Edit, Write, MultiEdit): tells the agent when the file it just changed is the source of a
# note published on the user's notes site
#
# The failure this exists to prevent: an agent edits a local report that was published with notes-publish, and
# nothing tells it a published copy exists. The copy on the site then drifts, silently, until the user finds
# an out-of-date page. notes-publish records each document's source file in
# $XDG_STATE_HOME/notes-publish/published.json (default ~/.local/state/notes-publish/); `notes-publish --where
# FILE` reads it and says which document FILE is and whether it still matches what was published.
#
# Never blocks and never asks. It adds one note to the model's context (hookSpecificOutput.additionalContext),
# at most once per session per file. The note tells the agent to report the drift and not to republish: a
# publish is the user's call (see claude/rules/artifacts.md, "Publishing is a separate, deliberate step").
#
# Cheap by design: a grep of published.json for the path runs first, and only a hit starts notes-publish.
# Not covered: edits made through Bash (sed, a script, a formatter) and files regenerated by a tool.
#
# Bash, not zsh, to match the hooks beside it. Written for bash 3.2 (macOS /bin/bash).

set -e

INPUT=$(cat)
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // empty')
SESSION_ID=$(printf '%s' "$INPUT" | jq -r '.session_id // empty')
[ -z "$FILE" ] && exit 0

PUBLISHED=${XDG_STATE_HOME:-$HOME/.local/state}/notes-publish/published.json
[ -r "$PUBLISHED" ] || exit 0
grep -qF "$FILE" "$PUBLISHED" || exit 0
command -v notes-publish >/dev/null 2>&1 || exit 0

FOUND=$(notes-publish --where "$FILE" 2>/dev/null) || exit 0
[ -z "$FOUND" ] && exit 0

STATE=${CLAUDE_CONFIG_DIR:-$HOME/.claude}/note-published-source-edited
MARK=$STATE/${SESSION_ID:-no-session}-$(printf '%s' "$FILE" | cksum | cut -d' ' -f1)
[ -f "$MARK" ] && exit 0
{
    mkdir -p "$STATE" &&
    find "$STATE" -type f -mtime +14 -delete &&
    : > "$MARK"
} 2>/dev/null || true

NOTE="$FOUND. Editing the local file does not change the published copy, so the page on the notes site now differs from it. Do not republish on your own initiative: finish the edit, then say in your reply that the published note is out of date and which file it comes from, and publish only when the user asks (notes-publish FILE; its audience is kept). This note appears once per session for this file."
jq -n --arg n "$NOTE" '{hookSpecificOutput: {hookEventName: "PostToolUse", additionalContext: $n}}'
