#!/usr/bin/env bash
#
# cloud-setup.sh — Provision a Claude Code cloud session VM (Anthropic-hosted, Ubuntu,
# runs as root) so its sessions carry this repo's rules, skills and commands.
#
# Run it from the cloud environment's setup script (claude.ai/code → environment →
# Setup script):
#
#   git clone --depth 1 https://github.com/mrtysn/agents-shared "$HOME/dev/agents-shared"
#   bash "$HOME/dev/agents-shared/scripts/cloud-setup.sh"
#
# Bash, not zsh: the VM has no zsh until this script installs it.
#
# What it does not do, and why:
#   • No settings.json and no hooks. A cloud session does not read ~/.claude/settings.json
#     (code.claude.com/docs/en/settings, "Settings in cloud sessions"); a repo that needs a
#     hook in the cloud commits it to its own .claude/settings.json.
#   • No pinned runtimes or engines. The image's node, python and pnpm build the repos;
#     a repo that needs a specific version or tool installs it from its own SessionStart
#     hook, gated on CLAUDE_CODE_REMOTE=true.
#
# Idempotent: safe to re-run in a session after `git pull`.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CLAUDE_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"

# ── Tools that rules and skills call ────────────────────────────────────────
# Several hooks and skill scripts are zsh; fzf and tree are used by skills.
missing=()
for tool in zsh fzf tree; do
    command -v "$tool" >/dev/null 2>&1 || missing+=("$tool")
done
if [ "${#missing[@]}" -gt 0 ]; then
    if command -v apt-get >/dev/null 2>&1; then
        apt-get update -qq
        DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${missing[@]}"
    else
        echo "cloud-setup: no apt-get here; install ${missing[*]} by hand" >&2
    fi
fi

# ── Rules, skills and commands into ~/.claude ───────────────────────────────
bash "$REPO_DIR/scripts/init-global.sh"

# ── $AGENTS_SHARED for the shell the Bash tool uses ─────────────────────────
# init-global.sh writes ~/.config/agents-shared/env.zsh, which only zsh sources.
ENV_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/agents-shared/env.zsh"
for profile in "$HOME/.bashrc" "$HOME/.zshrc"; do
    touch "$profile"
    grep -qF "$ENV_FILE" "$profile" || printf '\n[ -r "%s" ] && . "%s"\n' "$ENV_FILE" "$ENV_FILE" >> "$profile"
done

# ── paths.local.sh, read by agents-shared hooks a repo may run ──────────────
cat > "$CLAUDE_DIR/paths.local.sh" <<EOF
# Generated by agents-shared/scripts/cloud-setup.sh — do not edit.
AGENTS_SHARED_DIR="$REPO_DIR"
EOF

# ── User CLAUDE.md: what differs in a cloud session ─────────────────────────
# Loaded as user instructions in every cloud session (code.claude.com/docs/en/cloud-environments,
# "Add personal preferences without committing to the repo").
cat > "$CLAUDE_DIR/CLAUDE.md" <<'EOF'
# Cloud session

Generated by agents-shared/scripts/cloud-setup.sh. This session runs in a cloud VM, not
on the owner's Mac. The rules in ~/.claude/rules/ still apply, with these differences.

- **Branch, not main.** Commit each finished change and push it to this session's
  branch. Never push to `main`; this overrides "commit on the branch the repo is on,
  `main` included" in the commit rule.
- **Only this repo is here.** No sibling repos under ~/dev except agents-shared, no
  gitignored local files (`*.local.*`, data folders), no Doppler, no ssh to node01, no
  adb devices, no GUI apps. A rule or doc that names a local tool (`quiet-open`,
  `notes-publish`, `project-lifecycle`, `agent-auth`, `fetch-anything-agent`,
  `render-terminal-screen`) applies only where that tool exists: when it is missing, say
  so in the report instead of improvising a substitute.
- **No user hooks run.** The rules mention hooks that enforce them locally; here nothing
  enforces them but you.
- **No paid API calls and no live requests to third-party sites** unless the task says so.
EOF

printf '\n=== cloud-setup done ===\n  Claude dir: %s\n  Repo:       %s\n\n' "$CLAUDE_DIR" "$REPO_DIR"
